            <div class="card-body px-4">
                <p class="lead" style="font-size: 1.1rem; line-height: 1.7;">
                    Este relatório apresenta o desenvolvimento de um sistema baseado em Internet das Coisas (IoT) voltado ao monitoramento ambiental, com ênfase na variável de umidade do solo. O projeto dá continuidade a uma solução previamente implementada para coleta e visualização de dados, evoluindo para um sistema autônomo, embarcado e capaz de operar em campo.
                </p>
                <p>
                    O objetivo consiste em ampliar a aquisição de dados ambientais por meio de sensores físicos, integrando hardware e software em uma arquitetura robusta e escalável. A metodologia adotada segue as etapas ouvir, criar e implementar, contemplando diagnóstico com a comunidade externa, desenvolvimento do módulo sensor com microcontrolador ESP32 (Heltec LoRa V3) e testes em ambiente real.
                </p>
                <p>
                    O sistema utiliza comunicação híbrida via Wi‑Fi e LoRa, garantindo operação mesmo em cenários com baixa conectividade. Os resultados preliminares demonstram a viabilidade técnica da solução, com coleta contínua de dados, transmissão estável e integração com plataforma digital para visualização e análise. Conclui-se que a proposta contribui para o aprimoramento do monitoramento ambiental e apresenta potencial para aplicações em gestão hídrica e agricultura de precisão.
                </p>

